package app

import (
	"fmt"
	"math"
	"net/url"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"

	"screenpin/internal/process"
)

type videoEdit struct {
	format     string
	start, end float64
}

func (e videoEdit) trimmed() bool { return e.start > 0 || e.end > 0 }

func parseVideoEdit(q url.Values) (videoEdit, error) {
	e := videoEdit{format: q.Get("format")}
	switch e.format {
	case "":
		e.format = "mp4"
	case "mp4", "gif", "webp":
	default:
		return e, fmt.Errorf("不支持的导出格式")
	}
	for key, p := range map[string]*float64{"start": &e.start, "end": &e.end} {
		if value := q.Get(key); value != "" {
			v, err := strconv.ParseFloat(value, 64)
			if err != nil || math.IsNaN(v) || math.IsInf(v, 0) || v < 0 || (key == "end" && v == 0) {
				return e, fmt.Errorf("无效的裁剪时间")
			}
			*p = v
		}
	}
	if e.end > 0 && e.end-e.start < .049 {
		return e, fmt.Errorf("裁剪范围过短")
	}
	return e, nil
}

func runMediaExport(executable, destination string, args []string) error {
	tmp, err := os.CreateTemp(filepath.Dir(destination), ".screenpin-export-*"+filepath.Ext(destination))
	if err != nil {
		return err
	}
	name := tmp.Name()
	_ = tmp.Close()
	defer os.Remove(name)
	args = append([]string{"-hide_banner", "-loglevel", "error", "-nostdin", "-y"}, args...)
	cmd := exec.Command(executable, append(args, name)...)
	process.HideWindow(cmd)
	tail := &logTail{}
	cmd.Stderr = tail
	if err := cmd.Start(); err != nil {
		return err
	}
	release, err := process.Guard(cmd)
	if err != nil {
		_ = cmd.Process.Kill()
		_ = cmd.Wait()
		return err
	}
	defer release()
	if err := cmd.Wait(); err != nil {
		return fmt.Errorf("%w %s", err, strings.TrimSpace(tail.String()))
	}
	if info, err := os.Stat(name); err != nil || info.Size() == 0 {
		return fmt.Errorf("没有生成有效文件")
	}
	return os.Rename(name, destination)
}

func joinRecordingSegments(executable string, paths []string) (string, error) {
	if len(paths) == 1 {
		return paths[0], nil
	}
	directory := filepath.Dir(paths[0])
	list, err := os.CreateTemp(directory, "screenpin-*.ffconcat")
	if err != nil {
		return "", err
	}
	defer os.Remove(list.Name())
	for _, path := range paths {
		// All parts have names generated by startRecorder in the same draft directory.
		if _, err = fmt.Fprintf(list, "file '%s'\n", filepath.Base(path)); err != nil {
			_ = list.Close()
			return "", err
		}
	}
	if err = list.Close(); err != nil {
		return "", err
	}
	dest := strings.TrimSuffix(paths[0], ".mp4") + "_合并.mp4"
	if err = runMediaExport(executable, dest, []string{"-f", "concat", "-safe", "0", "-i", list.Name(), "-map", "0", "-c", "copy", "-movflags", "+faststart"}); err != nil {
		return "", fmt.Errorf("合并录制失败，分段草稿保留在 %s：%w", directory, err)
	}
	for _, path := range paths {
		_ = os.Remove(path)
	}
	return dest, nil
}

func exportRecording(source, destination string, e videoEdit) error {
	encoder, err := findFFmpeg()
	if err != nil {
		return err
	}
	args := []string{"-reinit_filter", "0", "-ss", fmt.Sprintf("%.3f", e.start), "-i", source}
	if e.end > 0 {
		args = append(args, "-t", fmt.Sprintf("%.3f", e.end-e.start))
	}
	motion := "fps=12,scale=w='min(iw,1280)':h='min(ih,1280)':force_original_aspect_ratio=decrease:flags=lanczos"
	if e.format != "mp4" {
		args = []string{"-reinit_filter", "0", "-i", source}
		if e.trimmed() {
			trim := fmt.Sprintf("trim=start=%.3f", e.start)
			if e.end > 0 {
				trim += fmt.Sprintf(":end=%.3f", e.end)
			}
			motion = trim + ",setpts=PTS-STARTPTS," + motion
		}
	}
	switch e.format {
	case "mp4":
		args = append(args, "-map", "0:v:0", "-map", "0:a:0?", "-c:v", "libx264", "-preset", "veryfast", "-crf", "16", "-c:a", "aac", "-b:a", "128k", "-movflags", "+faststart")
	case "gif":
		// Build the palette separately to avoid buffering every video frame.
		paletteFile, err := os.CreateTemp(filepath.Dir(source), "screenpin-palette-*.png")
		if err != nil {
			return err
		}
		palette := paletteFile.Name()
		_ = paletteFile.Close()
		defer os.Remove(palette)
		paletteArgs := append(append([]string(nil), args...), "-vf", motion+",palettegen", "-an", "-frames:v", "1", "-update", "1")
		if err = runMediaExport(encoder, palette, paletteArgs); err != nil {
			return err
		}
		args = append(args, "-i", palette, "-filter_complex", "[0:v]"+motion+"[v];[v][1:v]paletteuse", "-an", "-loop", "0")
	case "webp":
		args = append(args, "-vf", motion, "-an", "-c:v", "libwebp_anim", "-quality", "80", "-loop", "0")
	}
	return runMediaExport(encoder, destination, args)
}
